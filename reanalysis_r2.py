    for l in LAGSETS:
        a, b = cname("LR", e, l), cname("RF", e, l)
        t1, t24 = dm_test(yte, pte[a], pte[b], 0), dm_test(yte, pte[a], pte[b], 24)
        p1, p24 = dm_test(yo, oos[a][OOS], oos[b][OOS], 0), dm_test(yo, oos[a][OOS], oos[b][OOS], 24)
        fa = folds[folds.config == a].set_index("month").RMSE; fb = folds[folds.config == b].set_index("month").RMSE
