# =============================================================================== 1. DATA (shared loader, rounded hour)
D = rc.load_data(XLSX)
raw, df, n_raw, n_jitter, n_hour_shift = D["raw"], D["df"], D["n_raw"], D["n_jitter"], D["n_hour_shift"]
n = len(df)

ENCS = ["int", "onehot", "cyclic"]
CAL = {e: rc.calendar(df, e) for e in ENCS}
def X_of(enc, lagset): return pd.concat([CAL[enc], df[LAGSETS[lagset]]], axis=1)

CONFIGS = [(m, e, l) for m in ("LR", "RF") for e in ENCS for l in LAGSETS]   # 18 model configurations
def cname(m, e, l): return f"{m} / {e} / {l}"

def make_model(m, params=None):
    if m == "LR": return LinearRegression()
    p = dict(n_estimators=N_TREES, random_state=SEED, n_jobs=-1); p.update(params or {})
    return RandomForestRegressor(**p)

def bench_pred(fit_idx, ev_idx): return rc.bench_pred(df, fit_idx, ev_idx)
def idx(sl): return np.arange(n)[sl]

