"""Round-2 reanalysis: HVAC hourly active-power baseline (BAS-only features), LR vs RF.

Addresses reviewer points: data audit, calendar encoding (integer / one-hot / cyclical),
train-validation-test selection, rolling-origin evaluation, Diebold-Mariano tests,
benchmarks (mean, persistence), lag ablation, ASHRAE Guideline 14 metrics,
Oct-Dec test-window check, and corrected deviation metrics.

The original pipeline (reanalysis.py -> results.json, figures/fig*.png) is NOT touched.
Everything here is written to reanalysis_r2/ and reanalysis_summary.md.

Usage:  python reanalysis_r2.py ["Perhitungan LR vs RF.xlsx"]
"""
